// Dumps the compiled BLOCK_REFLOWS table (4 x 12 x 12 slots) from the web source into a
// compact Swift literal so the native wall can reproduce the exact same re-flow arrangements.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../src/components/wall');

const strip = (file) => readFileSync(file, 'utf8')
    .replace(/^import type .*$/gm, '')
    .replace(/^export /gm, '')
    .replace(/^const BLOCK_REFLOWS\s*:\s*[^=]+=/m, 'const BLOCK_REFLOWS =');

const code = `${strip(resolve(src, 'blockReflows.ts'))}\n;globalThis.__R = BLOCK_REFLOWS;`;
const fn = new Function(code);
fn();
const table = globalThis.__R;

const rows = table.map((perSlot, t) => {
    const slots = perSlot.map((entry, s) => {
        const body = entry.map(slot => `BlockSlot(x: ${slot.x}, y: ${slot.y}, cols: ${slot.cols}, rows: ${slot.rows})`).join(', ');
        return `        // ${t}:${s}\n        [${body}],`;
    }).join('\n');
    return `    // 变体 ${t}\n    [\n${slots}\n    ],`;
});

const out = `// Generated by Tools/dump_reflows.mjs — do not edit by hand.
//
// For each base template (4), for each expandable slot (12), the arrangement every card in
// that block falls back to while the slot is open. The expanded card always takes the 6x6
// gear; the other eleven degrade so the block stays exactly covered.

import Foundation

enum BlockReflows {
    static let table: [[[BlockSlot]]] = [
${rows.join('\n')}
    ]
}
`;

writeFileSync(resolve(here, '../Sources/Wall/BlockReflows.swift'), out, 'utf8');
console.log('wrote', table.length, 'templates x', table[0].length, 'slots x', table[0][0].length, 'cards');
